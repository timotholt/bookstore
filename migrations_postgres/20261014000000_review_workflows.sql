ALTER TABLE reviews ADD CONSTRAINT reviews_user_fk FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE;
ALTER TABLE review_votes ADD CONSTRAINT review_votes_user_fk FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE;
ALTER TABLE reviews ADD CONSTRAINT reviews_work_user_unique UNIQUE(work_key,user_id);
ALTER TABLE reviews ADD COLUMN deleted_at TIMESTAMPTZ;
