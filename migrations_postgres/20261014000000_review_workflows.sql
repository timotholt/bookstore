CREATE FUNCTION review_title_key(title TEXT, author TEXT, book_id TEXT)
RETURNS TEXT LANGUAGE SQL IMMUTABLE PARALLEL SAFE AS $$
 SELECT md5(json_build_array(
   lower(regexp_replace(btrim(title), '\s+', ' ', 'g')),
   CASE WHEN btrim(author) = '' THEN 'unknown-author:' || book_id
        ELSE lower(regexp_replace(btrim(author), '\s+', ' ', 'g')) END
 )::text)
$$;
