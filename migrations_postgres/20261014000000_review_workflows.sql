ALTER TABLE reviews ADD COLUMN published_revision BIGINT;
CREATE TABLE review_revisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 review_id BIGINT NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
 rating INTEGER NOT NULL CHECK(rating BETWEEN 1 AND 5),
 title TEXT NOT NULL CHECK(char_length(title) <= 120),
 body TEXT NOT NULL CHECK(char_length(body) <= 5000),
 status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','published','rejected','superseded')),
 reason TEXT NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(review_id,id)
);
ALTER TABLE reviews ADD CONSTRAINT review_current_revision_fk FOREIGN KEY(id,current_revision) REFERENCES review_revisions(review_id,id) DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE reviews ADD CONSTRAINT review_published_revision_fk FOREIGN KEY(id,published_revision) REFERENCES review_revisions(review_id,id) DEFERRABLE INITIALLY DEFERRED;
CREATE TABLE review_moderators (
 user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 granted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE review_moderation_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 review_id BIGINT NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
 revision_id BIGINT REFERENCES review_revisions(id) ON DELETE CASCADE,
 actor_id TEXT REFERENCES users(id) ON DELETE SET NULL,
 action TEXT NOT NULL CHECK(action IN ('approve','reject','remove','delete','report_resolved')),
 reason TEXT NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE review_reports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 review_id BIGINT NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
 revision_id BIGINT NOT NULL REFERENCES review_revisions(id) ON DELETE CASCADE,
 user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 reason TEXT NOT NULL CHECK(char_length(reason) BETWEEN 3 AND 1000),
 status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','resolved')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 resolved_at TIMESTAMPTZ,
 UNIQUE(review_id,revision_id,user_id)
);
CREATE TABLE review_work_aggregates (
 work_key TEXT PRIMARY KEY REFERENCES review_works(work_key) ON DELETE CASCADE,
 published_count BIGINT NOT NULL DEFAULT 0,
 rating_sum BIGINT NOT NULL DEFAULT 0,
 average_rating DOUBLE PRECISION NOT NULL DEFAULT 0,
 star_1_count BIGINT NOT NULL DEFAULT 0,
 star_2_count BIGINT NOT NULL DEFAULT 0,
 star_3_count BIGINT NOT NULL DEFAULT 0,
 star_4_count BIGINT NOT NULL DEFAULT 0,
 star_5_count BIGINT NOT NULL DEFAULT 0,
 CHECK(published_count >= 0 AND rating_sum >= 0 AND average_rating BETWEEN 0 AND 5)
);
CREATE INDEX reviews_work_public ON reviews(work_key,published_at DESC,id DESC) WHERE status='published' AND deleted_at IS NULL;
CREATE INDEX review_revisions_pending ON review_revisions(created_at,id) WHERE status='pending';
CREATE INDEX review_reports_open ON review_reports(created_at,id) WHERE status='open';
CREATE INDEX review_events_history ON review_moderation_events(review_id,id DESC);
-- Also covers account deletion through existing cascades. The shared work row
-- serializes all mutations before this aggregate rebuild under READ COMMITTED.
CREATE FUNCTION refresh_review_work() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE k TEXT;
BEGIN
 k := COALESCE(NEW.work_key, OLD.work_key);
 PERFORM 1 FROM review_works WHERE work_key=k FOR UPDATE;
 INSERT INTO review_work_aggregates
 SELECT k,count(*),COALESCE(sum(rating),0),COALESCE(avg(rating),0),
 count(*) FILTER(WHERE rating=1),count(*) FILTER(WHERE rating=2),
 count(*) FILTER(WHERE rating=3),count(*) FILTER(WHERE rating=4),count(*) FILTER(WHERE rating=5)
 FROM reviews WHERE work_key=k AND status='published' AND deleted_at IS NULL
 ON CONFLICT(work_key) DO UPDATE SET
 published_count=EXCLUDED.published_count,rating_sum=EXCLUDED.rating_sum,
 average_rating=EXCLUDED.average_rating,star_1_count=EXCLUDED.star_1_count,
 star_2_count=EXCLUDED.star_2_count,star_3_count=EXCLUDED.star_3_count,
 star_4_count=EXCLUDED.star_4_count,star_5_count=EXCLUDED.star_5_count;
 RETURN NULL;
END $$;
CREATE TRIGGER reviews_aggregate AFTER INSERT OR UPDATE OR DELETE ON reviews
FOR EACH ROW EXECUTE FUNCTION refresh_review_work();
